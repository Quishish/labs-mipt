import numpy as np
import matplotlib.pyplot as plt

# Настройки стиля
plt.rcParams.update({'font.size': 15})

# =============================================================================
# Функция расчёта χ² СТРОГО по исходному алгоритму
# =============================================================================
def fun(arrx, arry, ch):
    """
    Линейная аппроксимация МНК + χ² по оригинальному алгоритму:
    - Коэффициенты через ручное усреднение
    - χ² = Σ[(yᵢ − (a·xᵢ+b))² / 0.03²]
    - Возвращает √χ² (корень!)
    """
    x = arrx
    y = arry

    xy_av = 0
    x_2_av = 0
    y_2_av = 0
    x_av = 0
    y_av = 0
    
    for i in range(len(arrx)):
        x_av += x[i]
        y_av += y[i]
        xy_av += x[i] * y[i]
        x_2_av += x[i] * x[i]
        y_2_av += y[i] * y[i]
    
    x_av /= len(x)
    y_av /= len(y)
    xy_av /= len(x)
    x_2_av /= len(x)
    y_2_av /= len(x)

    a = (xy_av - x_av * y_av) / (x_2_av - x_av ** 2)
    b = y_av - a * x_av

    sigma_b = 1/((len(x))**0.5) * ((y_2_av - y_av**2) / (x_2_av - x_av ** 2) - b**2) ** 0.5
    sigma_a = sigma_b * (x_2_av - x_av**2)**0.5

    hi = 0
    for i in range(len(arrx)):
        hi += (arry[i] - (a*arrx[i]+b))**2 / (0.03)**2
    
    if ch:
        print(f"√χ² = {hi**0.5:.3f} (n = {len(arrx)})")
        print(f"Коэффициент наклона μ = {a:.4e}")
        print(f"Погрешность наклона σ_μ = {sigma_a:.4e}")

    return a, b, hi**0.5


# =============================================================================
# Исходные данные
# =============================================================================
t = np.array([2*60+7, 2*60+23, 3*60+10, 5*60+7])  # время, с
V = np.array([26, 26, 25, 25])                      # объём, мл
h = np.array([56, 49, 40, 28])                      # высота, мм

# Расчёт расхода воды: Q = V/t
Q = V / t

# Погрешности для графика
err_Q = Q * (0.1 / h)   # относительная погрешность расхода
err_h = 0.05            # погрешность высоты, мм

# =============================================================================
# Расчёт по функции fun()
# =============================================================================
print("=== Обработка данных ===")
print(f"t, с:  {t}")
print(f"V, мл: {V}")
print(f"h, мм: {h}")
print(f"Q=V/t: {Q}\n")

# Вызов функции: h — аргумент, Q — значение, ch=True для вывода статистики
mu, Q0, chi_sqrt = fun(h, Q, ch=True)

# =============================================================================
# Вывод уравнения с полученными коэффициентами
# =============================================================================
print("\n=== Уравнение линейной зависимости ===")
if Q0 >= 0:
    print(f"Q = {mu:.4f}·h + {Q0:.4f}")
else:
    print(f"Q = {mu:.4f}·h {Q0:.4f}")
print(f"или в экспоненциальной форме:")
if Q0 >= 0:
    print(f"Q = {mu:.4e}·h + {Q0:.4e}")
else:
    print(f"Q = {mu:.4e}·h {Q0:.4e}")

# =============================================================================
# Построение графика
# =============================================================================
plt.figure(figsize=(12, 10))

# Экспериментальные точки с погрешностями
plt.errorbar(
    h, Q,
    xerr=err_h, yerr=err_Q,
    fmt='o', capsize=4, markersize=8,
    color='blue', ecolor='gray', alpha=0.8,
    label='Экспериментальные данные'
)

# Линия аппроксимации по коэффициентам из fun()
h_fit = np.linspace(np.min(h) - 5, np.max(h) + 5, 100)
Q_fit = mu * h_fit + Q0
plt.plot(
    h_fit, Q_fit, 'r-', linewidth=2, alpha=0.9,
    label=f'Аппроксимация: $Q = {mu:.4f}h {Q0:+.4f}$'
)

# Оформление графика
plt.xlabel('Высота столба $h$, мм', fontsize=15)
plt.ylabel('Расход воды $Q$, мл/с', fontsize=15)
plt.title('Зависимость расхода воды от высоты столба', fontsize=18)
plt.grid(axis='y', linestyle='--', alpha=0.3)
plt.legend(fontsize=12)
plt.tight_layout()

# Сохранение и отображение
plt.savefig('fit_fun_original.png', dpi=150, bbox_inches='tight')
plt.show()